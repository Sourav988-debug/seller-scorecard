CREATE WAREHOUSE IF NOT EXISTS SCORECARD_WH WAREHOUSE_SIZE='XSMALL' AUTO_SUSPEND=60 AUTO_RESUME=TRUE INITIALLY_SUSPENDED=TRUE;
CREATE DATABASE IF NOT EXISTS SELLER_SCORECARD_DB; USE DATABASE SELLER_SCORECARD_DB;
CREATE SCHEMA IF NOT EXISTS RAW; CREATE SCHEMA IF NOT EXISTS CURATED; CREATE SCHEMA IF NOT EXISTS ANALYTICS;
CREATE STAGE IF NOT EXISTS RAW.GOLD_STAGE FILE_FORMAT=(TYPE=CSV SKIP_HEADER=1 FIELD_OPTIONALLY_ENCLOSED_BY='"');
CREATE TABLE IF NOT EXISTS RAW.GOLD_SELLER_MONTH_RAW (seller_id STRING,seller_state STRING,month DATE,orders INT,revenue FLOAT,late_orders INT,late_rate FLOAT,avg_review_score FLOAT);
COPY INTO RAW.GOLD_SELLER_MONTH_RAW FROM @RAW.GOLD_STAGE PATTERN='.*gold_seller_month.*\\.csv(\\.gz)?' ON_ERROR='ABORT_STATEMENT';
CREATE TABLE IF NOT EXISTS ANALYTICS.GOLD_SELLER_MONTH AS SELECT * FROM RAW.GOLD_SELLER_MONTH_RAW;
CREATE ROLE IF NOT EXISTS SCORECARD_ANALYST_ROLE;
GRANT USAGE ON WAREHOUSE SCORECARD_WH TO ROLE SCORECARD_ANALYST_ROLE;
GRANT USAGE ON DATABASE SELLER_SCORECARD_DB TO ROLE SCORECARD_ANALYST_ROLE;
GRANT USAGE ON SCHEMA ANALYTICS TO ROLE SCORECARD_ANALYST_ROLE;
GRANT SELECT ON ALL TABLES IN SCHEMA ANALYTICS TO ROLE SCORECARD_ANALYST_ROLE;
GRANT SELECT ON FUTURE TABLES IN SCHEMA ANALYTICS TO ROLE SCORECARD_ANALYST_ROLE;